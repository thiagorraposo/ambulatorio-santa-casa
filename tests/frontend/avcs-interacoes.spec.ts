import { expect, test } from '@playwright/test';
import { apiJson, seedPatient, seedAttendance, signIn, assertAccessible, assertFitsViewport } from './stage7-helpers';
test('E4U AVC: teclado, rascunho, revisão, zoom e duas intenções preservadas', async ({ page }, info) => {
  const p = await seedPatient('AVC visual e interação'); const a = await seedAttendance(p.path);
  const path = `${p.path}/avcs`;
  const writes: string[] = [];
  page.on('request', r => { if (r.method() === 'POST' && new URL(r.url()).pathname === `/v1${path}`) writes.push(r.headers()['x-operacao-id'] ?? ''); });
  await signIn(page, 'edicao', a.path);
  await page.getByRole('link', { name: 'AVC do paciente (longitudinal)', exact: true }).click();
  await page.getByRole('link', { name: 'Registrar AVC', exact: true }).click();
  await page.getByLabel('Ano do último AVC informado', { exact: true }).fill('2020');
  const presence = page.getByLabel('AVC informado', { exact: true });
  await presence.focus(); await page.keyboard.press('Home'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
  await expect(presence).toHaveValue('nao');
  await expect(page.getByLabel('Ano do último AVC informado', { exact: true })).toHaveValue('2020');
  await page.getByLabel('Descrição do registro', { exact: true }).fill('Relato sintético independente da negativa');
  const discard = page.getByRole('button', { name: 'Descartar rascunho', exact: true });
  await discard.click();
  await expect(page.getByRole('button', { name: 'Continuar editando', exact: true })).toBeFocused();
  await page.keyboard.press('Escape'); await expect(discard).toBeFocused();
  await page.getByRole('link', { name: '← Voltar aos episódios', exact: true }).click();
  await page.getByRole('dialog', { name: 'Alterações não salvas', exact: true }).getByRole('button', { name: 'Sair e manter rascunho', exact: true }).click();
  await page.getByRole('link', { name: 'Registrar AVC', exact: true }).click();
  await expect(presence).toHaveValue('nao');
  await expect(page.getByLabel('Descrição do registro', { exact: true })).toHaveValue('Relato sintético independente da negativa');
  for (const width of [1440,390,320]) {
    await page.setViewportSize({ width, height: width===1440 ? 960 : 844 });
    await assertFitsViewport(page); await assertAccessible(page);
    await page.screenshot({ path: info.outputPath(`avc-formulario-${width}.png`), fullPage: true });
  }
  await page.getByRole('button', { name: 'Revisar AVC', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Revisão do registro de AVC', exact: true })).toBeFocused();
  await page.setViewportSize({ width:1280,height:900 }); await page.evaluate(() => { document.documentElement.style.zoom='2'; });
  await assertFitsViewport(page); await assertAccessible(page);
  await page.screenshot({ path: info.outputPath('avc-revisao-zoom200.png'), fullPage:true });
  expect(writes).toHaveLength(0);
  await page.evaluate(() => { document.documentElement.style.zoom=''; });
  const first = page.waitForResponse(r => r.request().method()==='POST' && new URL(r.url()).pathname===`/v1${path}`);
  await page.getByRole('button', { name:'Confirmar AVC',exact:true }).click(); expect((await first).status()).toBe(201);
  await page.getByRole('button', { name:'Registrar outro episódio',exact:true }).click();
  await page.getByLabel('Ano do último AVC informado', { exact:true }).fill('2021');
  await page.getByRole('button', { name:'Revisar AVC',exact:true }).click();
  const second = page.waitForResponse(r => r.request().method()==='POST' && new URL(r.url()).pathname===`/v1${path}`);
  await page.getByRole('button', { name:'Confirmar AVC',exact:true }).click(); expect((await second).status()).toBe(201);
  expect(writes).toHaveLength(2); expect(new Set(writes).size).toBe(2);
  await expect(page.getByRole('heading', { name:/Registro confirmado/ })).toHaveCount(2);
  const rows = await apiJson<Array<{ ocorreu:boolean|null;anoEvento:number }>>('GET',path);
  expect(rows.map(r=>[r.ocorreu,r.anoEvento])).toEqual([[null,2021],[false,2020]]);
});
